//! Per-language word lists, comment leader, quotes and devicon.

use std::path::Path;

use super::Hl;

const BLOCK_COMMENT: (&str, &str, Hl) = ("/*", "*/", Hl::Comment);
const HTML_COMMENT: (&str, &str, Hl) = ("<!--", "-->", Hl::Comment);

/// Extra rules beyond the word lists, for languages that are not code.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Code,
    /// `key:` / `key =` (and `"key":`) are properties, `[section]` a type.
    Config,
    /// `<tag` and `</tag` are keywords, `attr=` a property.
    Markup,
    /// Lines starting with `#` are headings.
    Markdown,
}

pub struct Lang {
    /// Nerd Font devicon and its nvim-web-devicons color.
    pub icon: char,
    pub icon_color: u32,
    /// Line comment leader; empty when the language only has block comments.
    pub comment: &'static str,
    /// String delimiters; also the quotes autopairs closes in this language.
    pub quotes: &'static str,
    pub macros: bool,
    /// Multi-line regions: (open, close, group), tried before anything else on a line.
    pub regions: &'static [(&'static str, &'static str, Hl)],
    /// Word lists, lowercase when `ignore_case`.
    pub keywords: &'static [&'static str],
    pub builtins: &'static [&'static str],
    pub consts: &'static [&'static str],
    pub ignore_case: bool,
    pub kind: Kind,
}

