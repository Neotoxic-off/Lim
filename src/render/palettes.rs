#[cfg(test)]
mod tests {
    use super::THEMES;

    #[test]
    fn every_theme_has_the_same_keys_in_order() {
        let first: Vec<&str> = THEMES[0].colors.iter().map(|(k, _)| *k).collect();
        assert_eq!(first.len(), 36);
        for theme in THEMES {
            let keys: Vec<&str> = theme.colors.iter().map(|(k, _)| *k).collect();
            assert_eq!(keys, first, "{}", theme.name);
        }
    }

    #[test]
    fn names_are_unique() {
        for (i, a) in THEMES.iter().enumerate() {
            assert!(
                THEMES[i + 1..].iter().all(|b| b.name != a.name),
                "duplicate {}",
                a.name
            );
        }
    }
}
